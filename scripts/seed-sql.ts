// Writes supabase/seed.sql from the demo data in src/lib/seed.ts.
//   npm run db:seed-sql
// Dates are written relative to now() (e.g. now() + 3 days), so the rounds are open whenever you load the seed —
// exactly like the localStorage demo. Each demo account also gets a Supabase Auth login with its demo password.
import { writeFileSync } from "node:fs";
import { createSeed } from "../src/lib/seed.ts";

const NOW = new Date();
const db = createSeed(NOW);

type V = string | number | boolean | null | undefined | object;

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lit = (v: V): string => {
  if (v === undefined || v === null) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "string") return q(v);
  return `${q(JSON.stringify(v))}::jsonb`;
};
const textArr = (a?: string[]) => (a && a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
/** ISO timestamp → now() ± seconds, so the seed stays current. */
const ts = (iso?: string) => {
  if (!iso) return "null";
  const s = Math.round((new Date(iso).getTime() - NOW.getTime()) / 1000);
  return s === 0 ? "now()" : `now() ${s < 0 ? "-" : "+"} interval '${Math.abs(s)} seconds'`;
};
/** YYYY-MM-DD → current_date ± days. */
const day = (d?: string) => {
  if (!d) return "null";
  const today = Date.UTC(NOW.getFullYear(), NOW.getMonth(), NOW.getDate());
  const [y, m, dd] = d.split("-").map(Number);
  const n = Math.round((Date.UTC(y, m - 1, dd) - today) / 86_400_000);
  return n === 0 ? "current_date" : `current_date ${n < 0 ? "-" : "+"} ${Math.abs(n)}`;
};

function insert(table: string, cols: string[], rows: string[][]) {
  if (!rows.length) return `-- ${table}: no rows\n`;
  return `insert into public.${table} (${cols.join(", ")}) values\n${rows.map((r) => `  (${r.join(", ")})`).join(",\n")};\n`;
}

const out: string[] = [];
out.push(`-- Generated by scripts/seed-sql.ts on ${NOW.toISOString()} — do not edit by hand, re-run npm run db:seed-sql.
-- Demo data for a TEST project only: every demo account gets its demo password.
-- Run after the migrations (SQL editor, or supabase db reset).

begin;

truncate public.ticket_messages, public.support_tickets, public.access_requests, public.emails, public.announcements,
  public.events, public.selections, public.rounds, public.courses, public.option_groups, public.profiles,
  public.professors, public.programmes, public.school_settings restart identity cascade;
delete from auth.identities where user_id in (select id from auth.users where raw_app_meta_data ->> 'seed' = 'option-demo');
delete from auth.users where raw_app_meta_data ->> 'seed' = 'option-demo';
`);

out.push(insert("school_settings", ["name", "contact"], [[lit(db.school), lit(db.schoolContact)]]));

out.push(insert(
  "programmes",
  ["id", "department", "name", "short", "degree", "ects", "duration", "regime", "academic_year", "location", "scientific_area", "contacts", "description", "learning_outcomes", "higher_education", "careers", "created_at"],
  db.programmes.map((p) => [
    lit(p.id), lit(p.department), lit(p.name), lit(p.short), lit(p.degree), lit(p.ects), lit(p.duration), lit(p.regime),
    lit(p.academicYear), lit(p.location), lit(p.scientificArea), lit(p.contacts ?? []), lit(p.description),
    textArr(p.learningOutcomes), lit(p.higherEducation), textArr(p.careers), p.createdAt ? ts(p.createdAt) : "now()",
  ]),
));

out.push(insert(
  "professors",
  ["id", "name", "title", "email", "area", "office", "photo", "bio"],
  db.professors.map((p) => [lit(p.id), lit(p.name), lit(p.title), lit(p.email), lit(p.area), lit(p.office), lit(p.photo), lit(p.bio)]),
));

out.push(insert(
  "profiles",
  ["id", "username", "name", "email", "role", "photo", "programme_id", "year", "title", "bio", "about", "aspiration", "bachelor", "dob", "past_options", "professor_id", "active", "invited_at", "created_at"],
  db.users.map((u) => [
    lit(u.id), lit(u.username), lit(u.name), lit(u.email), lit(u.role), lit(u.photo), lit(u.programmeId), lit(u.year),
    lit(u.title), lit(u.bio), lit(u.about), lit(u.aspiration), lit(u.bachelor), u.dob ? `${q(u.dob)}::date` : "null",
    lit(u.pastOptions ?? {}), lit(u.professorId), lit(u.active ?? true), ts(u.invitedAt), u.createdAt ? ts(u.createdAt) : "now()",
  ]),
));

out.push(insert(
  "option_groups",
  ["id", "programme_id", "year", "semester", "name", "ects"],
  db.groups.map((g) => [lit(g.id), lit(g.programmeId), lit(g.year), lit(g.semester), lit(g.name), lit(g.ects)]),
));

out.push(insert(
  "courses",
  ["id", "programme_id", "code", "name", "year", "semester", "area", "ects", "group_id", "capacity", "requires_approval", "course_director", "professor_id", "request_prompt", "description", "image", "details"],
  db.courses.map((c) => [
    lit(c.id), lit(c.programmeId), lit(c.code), lit(c.name), lit(c.year), lit(c.semester), lit(c.area), lit(c.ects), lit(c.groupId),
    lit(c.capacity), lit(c.requiresApproval), lit(c.courseDirector), lit(c.professorId), lit(c.requestPrompt), lit(c.description),
    lit(c.image), lit(c.details ?? {}),
  ]),
));

out.push(insert(
  "rounds",
  ["id", "programme_id", "year", "semester", "label", "opens_at", "closes_at", "email_sent_at"],
  db.rounds.map((r) => [lit(r.id), lit(r.programmeId), lit(r.year), lit(r.semester), lit(r.label), ts(r.opensAt), ts(r.closesAt), ts(r.emailSentAt)]),
));

out.push(insert(
  "selections",
  ["id", "student_id", "course_id", "status", "motivation", "note", "created_at", "decided_at"],
  db.selections.map((s) => [lit(s.id), lit(s.studentId), lit(s.courseId), lit(s.status), lit(s.motivation), lit(s.note), ts(s.createdAt), ts(s.decidedAt)]),
));

out.push(insert(
  "emails",
  ["id", "to_ids", "to_addresses", "subject", "body", "sent_at", "kind"],
  db.emails.map((m) => [lit(m.id), textArr(m.to), textArr(m.toAddresses), lit(m.subject), lit(m.body), ts(m.sentAt), lit(m.kind)]),
));

out.push(insert(
  "events",
  ["id", "programme_id", "date", "end_date", "time", "title", "description", "kind", "audience", "location", "created_by"],
  db.events.map((e) => [lit(e.id), lit(e.programmeId), day(e.date), day(e.endDate), lit(e.time), lit(e.title), lit(e.description), lit(e.kind), lit(e.audience), lit(e.location), lit(e.createdBy)]),
));

out.push(insert(
  "announcements",
  ["id", "programme_id", "title", "body", "audience", "pinned", "created_at", "author_id"],
  db.announcements.map((a) => [lit(a.id), lit(a.programmeId), lit(a.title), lit(a.body), lit(a.audience), lit(a.pinned ?? false), ts(a.createdAt), lit(a.authorId)]),
));

out.push(insert(
  "support_tickets",
  ["id", "user_id", "name", "email", "role", "programme_id", "topic", "subject", "page", "status", "created_at", "updated_at"],
  db.tickets.map((t) => [lit(t.id), lit(t.userId), lit(t.name), lit(t.email), lit(t.role), lit(t.programmeId), lit(t.topic), lit(t.subject), lit(t.page), lit(t.status), ts(t.createdAt), ts(t.updatedAt)]),
));

out.push(insert(
  "ticket_messages",
  ["ticket_id", "sender", "author_name", "body", "at"],
  db.tickets.flatMap((t) => t.messages.map((m) => [lit(t.id), lit(m.from), lit(m.authorName), lit(m.body), ts(m.at)])),
));

out.push(insert(
  "access_requests",
  ["id", "name", "email", "programme_id", "course_ids", "status", "created_at", "decided_at", "user_id"],
  (db.accessRequests ?? []).map((r) => [lit(r.id), lit(r.name), lit(r.email), lit(r.programmeId), textArr(r.courseIds), lit(r.status), ts(r.createdAt), ts(r.decidedAt), lit(r.userId)]),
));

// Supabase Auth logins for the demo accounts (email + demo password), linked through profiles.auth_id.
out.push(`
-- Auth logins for every demo account.
do $$
declare
  p record;
  uid uuid;
begin
  for p in select pr.id, pr.email, d.password from public.profiles pr
           join (values ${db.users.map((u) => `(${q(u.id)}, ${q(u.password)})`).join(", ")}) as d(id, password) on d.id = pr.id
  loop
    uid := gen_random_uuid();
    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
      confirmation_token, email_change, email_change_token_new, recovery_token)
    values ('00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', lower(p.email),
      extensions.crypt(p.password, extensions.gen_salt('bf')), now(),
      jsonb_build_object('provider', 'email', 'providers', jsonb_build_array('email'), 'seed', 'option-demo'),
      jsonb_build_object('profile_id', p.id), now(), now(), '', '', '', '');
    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), uid, uid::text,
      jsonb_build_object('sub', uid::text, 'email', lower(p.email), 'email_verified', true),
      'email', now(), now(), now());
    update public.profiles set auth_id = uid where id = p.id;
  end loop;
end $$;

commit;
`);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`supabase/seed.sql: ${db.programmes.length} Master's, ${db.users.length} people, ${db.groups.length} Opção slots, ${db.courses.length} courses, ${db.selections.length} selections, ${db.rounds.length} rounds`);
